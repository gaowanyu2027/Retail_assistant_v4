"""
意图路由器 — 用关键词规则把常见问题分流

目标：对命中强关键词的数据类问题，直接调用 skill 生成模板回答，
跳过 LLM 调用与等待，把常见查询的响应时间从秒级降到毫秒级。

分类：
- popularity / anomaly / emotion：数据查询（可模板化，零 LLM）
- report：热度汇报（可模板化，零 LLM）
- history / chat：仍走 Agent（需要理解），但可跳过向量召回
- general：完整 Agent 流程

规则保守：组合型问题（同时命中多个数据意图）一律归 general，交给 LLM 融合。
"""

# 强词：命中即判定该数据意图（几乎不会在无关语境出现，如"货架/告警/表情"）
_POP_STRONG = [
    "货架", "排名", "排行", "到访", "补货", "热销", "畅销",
    "人最多", "客流量", "哪个区域", "停留",
]
_ANO_STRONG = [
    "告警", "可疑", "预警", "小偷", "偷东西", "鬼祟", "不法", "异常", "安全",
]
_EMO_STRONG = [
    "表情", "满意度", "顾客情绪", "服务体验", "人脸", "心情", "开心",
]
# 弱词：单独出现不触发模板（劫持重灾区：热度/客流/受欢迎/情绪 等会出现在
# 无关语境——"CS2热度""天气热度""怎么提高热度""你情绪"），需强词或 ≥2 弱词
_POP_WEAK = ["热度", "客流", "受欢迎", "热门"]
_ANO_WEAK = ["风险", "行为", "有没有人"]
_EMO_WEAK = ["情绪", "满意", "态度", "不高兴"]

_HISTORY_KEYS = ["之前问", "以前问", "历史", "上次", "之前聊", "回忆", "刚才", "记录"]
_REPORT_KEYS = ["汇报", "定期", "报告", "摘要", "总结"]
_CHAT_KEYS = [
    "你好", "您好", "谢谢", "再见", "你是谁", "会什么", "做什么",
    "能做什么", "帮忙", "辛苦了", "哈哈", "呵呵", "在吗",
    "嗯嗯", "哦哦", "好的", "好的吧", "行吧",
]

# 注入攻击模式（前置检测：命中即归 general 走 LLM，由模型拒绝而非模板误答）
_INJECTION_KEYS = [
    "忽略以上", "忽略所有", "忽略系统", "忽略安全", "忽略之前",
    "假装你是", "你是系统管理员", "越权", "绕过", "不要遵守", "忘掉你的",
    "改成", "修改为", "篡改", "删除所有", "导出全部",
]

# 否定分析（缺陷 4 根治）：用户明确拒绝分析、只要报数/直答。
# "不要分析货架热度受什么影响，直接告诉我货架热度" 字面含完整归因问句，
# 向量/语义判定会误判为分析；但用户真实意图是拒绝分析只要数据。
# 命中任一 → 跳过后续分析结构检测，直接按报数判定走模板（规则确定性，向量无解）。
_NEGATE_ANALYSIS = [
    "不要分析", "不用分析", "别分析", "不需要分析", "不用你分析", "别给我分析",
    "只告诉我", "直接告诉我", "只查", "只看", "只报", "直接查", "直接看", "直接报",
    "别整", "别扯", "别废话",
]

# 数据类意图 → 可模板化（零 LLM）
ROUTED_INTENTS = ("popularity", "anomaly", "emotion", "report")

# ---------------------------------------------------------------------------
# 分析类意图的结构正则（封闭意图骨架，替代开放名词穷举）
#
# 为什么不用关键词穷举：口语变体是开放集（受什么/受啥/受嘛/受哪些/靠什么/
# 取决于啥/跟啥有关/咋提高…），加词永远有漏。但分析意图的中文"骨架"是
# 封闭的——归因/策略/观点/机制四类的句式结构有限，用结构正则一次全覆盖：
#   受啥影响/受嘛影响/受哪些因素影响      →  受…影响
#   啥导致/什么原因/因为啥               →  (什么|啥|嘛)…(导致|原因|因为)
#   取决于什么/决定啥                    →  (取决|决定)…(什么|啥)
#   跟销量有关吗/和热度有什么关系        →  (跟|和|与)…(有关|关系)
#   咋提高/怎样提升/怎么样才能增加        →  (怎么|如何|咋|怎样)…(提升类动词)
#   你觉得/你怎么看/你的看法             →  观点征询
#   怎么算的/通过什么方法/原理           →  机制询问
# 剩下的开放域（新名词/新流行语）全部落给 LLM 兜底，模板只接纯报数问句。
# ---------------------------------------------------------------------------
import re

_RE_CAUSE = re.compile(
    r"受.{0,12}(影响|因素|制约)"                                # 受什么/啥/嘛/哪些因素影响
    r"|(?:什么|啥|嘛|哪些|啥子).{0,8}(?:影响|导致|决定|因素|原因)"  # 啥导致/什么原因/哪些因素
    r"|(?:取决|决定).{0,3}于?.{0,5}(?:什么|啥|嘛|哪些)"          # 取决于什么/决定啥
    r"|(?:为什么|为啥|咋回事|怎么回事|什么原因|啥原因|嘛原因|怎么解释|因为啥|因为什么)"
    r"|(?:跟|和|与).{0,12}(?:什么|啥|嘛|哪些).{0,4}?(?:有关|相关|有关系|关系)"  # 跟什么有关
    r"|.{0,8}(?:和|与|跟).{0,8}(?:有关|相关|有关系|的关系)"       # 热度和销量有关吗
    r"|(?:靠|凭).{0,4}(?:什么|啥|嘛)"                            # 靠什么
    r"|原因|因素|分析|评估"                                      # 强归因词（单独出现即分析问）
    # 口语疑问词变体（封闭小集合，几十个封死；负例向量只抓 >0.75 极典型，
    # 0.6-0.7 的分析漏网必须由正则兜住，否则"货架热度咋个回事"会落进强词模板）
    r"|咋个|咋地|咋整|为啥子|搞什么|弄啥|啥情况|嘛情况|怎么个"
)

_RE_STRATEGY = re.compile(
    r"(?:怎么|如何|咋|怎样|咋样|怎么样)(?:才能)?.{0,8}"
    r"(?:提高|提升|增加|改善|优化|改进|减少|降低|增强|扩大|促销|推广|吸引|留住|布局|陈列|补货|定价|安排|卖|推)"
    r"|(?:怎么|如何|咋).{0,4}(?:办|做|弄|处理|调整|改)"
    r"|(?:有|给|求|要)(?:什么|点|个|些)?(?:建议|办法|方案|招|对策|想法)"
)

_RE_OPINION = re.compile(r"你觉得|你认为|你看|你的看法|咋看|怎么看|依你看")

_RE_MECHANISM = re.compile(
    r"怎么(?:算|判断|识别|检测|统计|得到|对比|工作|运作|计算|来的|生成的)"
    r"|(?:通过|用|靠|基于|根据|借助).{0,8}(?:什么|啥|嘛|哪些).{0,6}(?:方法|方式|手段|技术|原理|数据|算法)"
    r"|(?:原理|机制|工作方式|底层)"
)


def _hits(question: str, keys: list[str]) -> list[str]:
    return [k for k in keys if k in question]


def _semantic_check(q: str) -> bool:
    """语义闸：问句与分析问句范例语义相似 → True（建议降级 LLM）。

    任何异常（Ollama 不可用/导入失败）都返回 False 放行，语义闸只是
    正则之上的额外安全网，绝不阻塞主链路。
    """
    try:
        from agents.semantic_router import is_analysis_like
        return is_analysis_like(q)
    except Exception:
        return False


def route_intent(question: str) -> str:
    """返回意图：popularity / anomaly / emotion / report / history / chat / general"""
    q = (question or "").strip()
    if not q:
        return "general"

    # 纯符号/表情/标点输入（😂、！！！、😊🙏👍 等）→ chat 模板，确定性接管
    # （无法枚举 emoji：若问题中不含任何中文/字母/数字，则视为无意义输入）
    import re
    has_meaning = bool(re.search(r"[\u4e00-\u9fffA-Za-z0-9]", q))
    if q and not has_meaning:
        return "chat"

    # 注入攻击前置检测（先于一切数据意图，防模板误答注入句）
    if _hits(q, _INJECTION_KEYS):
        return "general"

    # 否定分析剥离（缺陷 4）："不要分析…直接告诉我…" → 用户拒绝分析只要报数，
    # 跳过分析结构检测，直接进入报数判定（模板）。剥离过度最坏落 general（LLM），
    # 不会劫持，安全。
    negated = bool(_hits(q, _NEGATE_ANALYSIS))

    # 归因/分析类问题（"受…影响/为什么/取决于…"）→ LLM（模板无法归因，只会报数）。
    # 结构正则一次覆盖全部口语变体（受啥/受嘛/受哪些因素/靠什么/跟…有关…），
    # 不再逐个穷举关键词——口语变体无限，意图骨架有限。
    if not negated and _RE_CAUSE.search(q):
        return "general"

    # 策略/建议类问题（"怎么提高/咋提升/给点建议…"）→ LLM（模板只会报当前值）
    if not negated and _RE_STRATEGY.search(q):
        return "general"

    # 人称元问题（"你情绪/我情绪"）+ 观点征询（"你觉得/你怎么看…"）
    # → LLM，模板会把"你情绪"误当顾客情绪查询、把"你觉得货架热度受啥影响"
    #    当货架排行（截图实测答非所问×5）
    if not negated and (_RE_OPINION.search(q) or _hits(q, [
        "你情绪", "你的情绪", "你开心", "你的心情", "你心情", "你感觉",
        "你怎么样", "感觉我", "我情绪", "我的情绪", "我今天",
    ])):
        return "general"

    # 无关话题前置：用户问与本店运营无关的内容（游戏/天气/其他店对比/世界排名等），
    # 但句中可能含"热度/客流"等数据词 → 归 general 由 LLM 澄清，
    # 避免"CS2热度怎么样"被模板报成货架排行（截图实测）
    if _hits(q, [
        "CS2", "游戏", "天气", "世界第一", "全世界", "其他店", "别的店",
        "别的超市", "其他门店", "别的门店", "外面", "网上",
    ]):
        return "general"

    # 机制/原理询问（"你怎么算的/通过什么方法/原理"）→ LLM 解释机制，
    # 模板只会报数据导致答非所问（实测"你是通过销量跟热度做对比判断转换率吗"
    # 曾因含"热度"被模板劫持，两次返回货架排行）
    if _RE_MECHANISM.search(q):
        return "general"

    # 过去时间限定 → LLM（系统只有实时数据，需模型诚实说明无历史而非模板报当前值）
    if _hits(q, ["去年", "上个月", "昨天", "前天", "上周", "上星期", "历史数据", "以前的数据"]):
        return "general"

    # 数据分析类问题（动线/时段/深度归因）→ LLM（模板只会报当前热度，无法回答分析结论）。
    # 必须在数据关键词判定之前，否则"逛完1号货架/客流高峰"会被"货架/客流"劫持走模板。
    if _hits(q, [
        "动线", "逛完", "逛了", "最常去", "怎么摆", "陈列", "交叉促销",
        "几点人最多", "客流高峰", "客流低谷", "什么时候补货", "排班",
        "看了很久", "停留很久", "不买", "刚需", "深度兴趣", "路过",
        "对比", "转化率",
    ]):
        return "general"

    # 历史回顾类（"我上次问…"）优先于数据关键词，避免被"客流/货架"劫持走模板
    if _hits(q, _HISTORY_KEYS):
        return "history"

    # 数据意图判定（保守化）：强词命中 或 弱词 ≥2 才走模板；
    # 弱词单独出现（如仅"热度"）→ 不判模板，走 LLM 由模型自行判断相关性，
    # 从源头消除"热度/客流"等弱词在无关语境被模板劫持的问题（截图实测五轮同类 bug）
    pop_s = _hits(q, _POP_STRONG)
    pop_w = _hits(q, _POP_WEAK)
    ano_s = _hits(q, _ANO_STRONG)
    ano_w = _hits(q, _ANO_WEAK)
    emo_s = _hits(q, _EMO_STRONG)
    emo_w = _hits(q, _EMO_WEAK)

    # 组合型问题（多个意图都有信号，含弱词信号）→ 交给 LLM 融合。
    # 必须先于模板阈值判定：否则"客流(弱)+告警(强)"会因弱词不构成 popularity
    # 而被误判为单意图 anomaly 走模板（保守化回归，实测 gen_06/mem_04）。
    intent_signals = sum([
        bool(pop_s) or bool(pop_w),
        bool(ano_s) or bool(ano_w),
        bool(emo_s) or bool(emo_w),
    ])
    if intent_signals >= 2:
        return "general"

    # 单意图模板命中（保守化）：强词命中 或 弱词 ≥2 才走模板；
    # 弱词单独出现（如仅"热度"）→ 不判模板，走 LLM 由模型自行判断相关性，
    # 从源头消除"热度/客流"等弱词在无关语境被模板劫持的问题（截图实测五轮同类 bug）
    pop = bool(pop_s) or len(pop_w) >= 2
    ano = bool(ano_s) or len(ano_w) >= 2
    emo = bool(emo_s) or len(emo_w) >= 2
    data_groups = [g for g in (pop, ano, emo) if g]

    if len(data_groups) >= 2:
        return "general"

    # 汇报类问题优先（"热度汇报"等同时含"热度"关键词，应归 report）
    report = bool(_hits(q, _REPORT_KEYS))
    template_hit = report or pop or ano or emo

    # 语义闸（L2）：正则判定可走模板后，再查一次"分析问句"语义相似度，
    # 相似 → 降级 LLM（抓正则漏网的口语变体，如"受嘛影响"）。
    # 只对模板候选查询；Ollama 不可用时自动放行（fail-open），不阻塞主链路。
    if template_hit and _semantic_check(q):
        return "general"

    if report:
        return "report"
    if pop:
        return "popularity"
    if ano:
        return "anomaly"
    if emo:
        return "emotion"
    if _hits(q, _CHAT_KEYS):
        return "chat"
    return "general"
